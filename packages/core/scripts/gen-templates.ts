/**
 * Regenerates src/templates/library.generated.ts from docs/Template-Library.md.
 * The Markdown stays the source of truth; a test fails if this file is stale.
 *
 *   pnpm --filter @dextra/core gen:templates
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { parseTemplateLibrary } from '../src/templates/parse-library'

const ROOT = resolve(import.meta.dirname, '../../..')
const SOURCE = resolve(ROOT, 'docs/Template-Library.md')
const OUT = resolve(import.meta.dirname, '../src/templates/library.generated.ts')

const templates = parseTemplateLibrary(readFileSync(SOURCE, 'utf8'))
const approvedIds = templates.filter((t) => t.status === 'approved').map((t) => t.id)

writeFileSync(
  OUT,
  `// Generated by scripts/gen-templates.ts from docs/Template-Library.md — do not edit by hand.

/** Ids the LLM may return: approved templates only. */
export const TEMPLATE_IDS = ${JSON.stringify(approvedIds)} as const

/** Raw records; validated by TemplateLibrarySchema when templates/index.ts loads. */
export const TEMPLATE_DATA: unknown = ${JSON.stringify(templates, null, 2)}
`,
)
console.log(`Wrote ${templates.length} templates (${approvedIds.length} approved)`)
