/**
 * Regenerates src/schema/iso-codes.ts from the ICU data bundled with Node.
 * ICU also knows historic / reserved codes, so those are removed explicitly and the
 * counts are asserted against the ISO standards (249 countries, 183 languages).
 *
 *   pnpm --filter @dextra/core gen:iso
 */
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const OUT = resolve(import.meta.dirname, '../src/schema/iso-codes.ts')
const LETTERS = 'abcdefghijklmnopqrstuvwxyz'.split('')
const pairs = LETTERS.flatMap((a) => LETTERS.map((b) => a + b))

/** Not ISO 3166-1 alpha-2: reserved, historic, or CLDR-only regions. */
const NOT_COUNTRIES = new Set(
  'ac an bu cp cq cs dd dg dy ea eu ez fx hv ic nh qo rh su ta tp uk un vd xa xb xk yd yu zr zz'.split(
    ' ',
  ),
)
/** Deprecated or withdrawn ISO 639-1 codes ICU still names. */
const NOT_LANGUAGES = new Set('bh in iw ji jw mo sh'.split(' '))

const named = (type: 'region' | 'language', code: string) => {
  try {
    const name = new Intl.DisplayNames(['en'], { type }).of(
      type === 'region' ? code.toUpperCase() : code,
    )
    return Boolean(name) && name?.toLowerCase() !== code
  } catch {
    return false
  }
}

const countries = pairs.filter((c) => !NOT_COUNTRIES.has(c) && named('region', c))
const languages = pairs.filter((c) => !NOT_LANGUAGES.has(c) && named('language', c))

if (countries.length !== 249) throw new Error(`expected 249 countries, got ${countries.length}`)
if (languages.length !== 183) throw new Error(`expected 183 languages, got ${languages.length}`)

const list = (codes: string[]) =>
  codes
    .reduce<string[]>((lines, code, i) => {
      if (i % 16 === 0) lines.push('')
      lines[lines.length - 1] += `'${code}', `
      return lines
    }, [])
    .map((l) => `  ${l.trim()}`)
    .join('\n')

writeFileSync(
  OUT,
  `// Generated by scripts/gen-iso.ts — do not edit by hand.

/** ISO 3166-1 alpha-2, lowercase (C1 → \`gl\`). */
export const COUNTRY_CODES = [
${list(countries)}
] as const

/** ISO 639-1 (C3 → \`hl\`). */
export const LANGUAGE_CODES = [
${list(languages)}
] as const

export type CountryCode = (typeof COUNTRY_CODES)[number]
export type LanguageCode = (typeof LANGUAGE_CODES)[number]
`,
)
console.log(`Wrote ${countries.length} countries, ${languages.length} languages`)
